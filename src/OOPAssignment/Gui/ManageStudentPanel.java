    private void addStudentBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addStudentBtnActionPerformed
    String name = nameTf.getText();
    String username = usernameTf.getText();
    String password = passwordTf.getText();
    String email = emailTf.getText();

    if (OOPAssignment.util.Validator.isEmpty(name)
            || OOPAssignment.util.Validator.isEmpty(username)
            || OOPAssignment.util.Validator.isEmpty(password)
            || OOPAssignment.util.Validator.isEmpty(email)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields!");
        return;
    }

    if (OOPAssignment.model.Student.findByUsername(username) != null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Username already exists!");
        return;
    }

    String studentId = OOPAssignment.model.Student.generateNextId();   // 自动生成,用户完全不用管

    OOPAssignment.model.Student newStudent = new OOPAssignment.model.Student(studentId, name, username, password, email);
    newStudent.save();

    javax.swing.JOptionPane.showMessageDialog(this, "Student added successfully! ID: " + studentId);
    nameTf.setText("");
    usernameTf.setText("");
    passwordTf.setText("");
    emailTf.setText("");
    refreshData();
    }//GEN-LAST:event_addStudentBtnActionPerformed

