    private void loadStudentBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loadStudentBtnActionPerformed
    String studentId = studentIdTf.getText();

    if (OOPAssignment.util.Validator.isEmpty(studentId)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter Student ID to search!");
        return;
    }

    OOPAssignment.model.Student foundStudent = OOPAssignment.model.Student.findByStudentId(studentId);

    if (foundStudent != null) {
        usernameTf.setText(foundStudent.getUsername());
        nameTf.setText(foundStudent.getName());
        emailTf.setText(foundStudent.getEmail());
        javax.swing.JOptionPane.showMessageDialog(this, "Student found! You can now edit and click Update.");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Student not found!");
    }
    }//GEN-LAST:event_loadStudentBtnActionPerformed

    private void updateStudentBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateStudentBtnActionPerformed
    String studentId = studentIdTf.getText();

    if (OOPAssignment.util.Validator.isEmpty(studentId)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter Student ID to update!");
        return;
    }

    OOPAssignment.model.Student existingStudent = OOPAssignment.model.Student.findByStudentId(studentId);

    if (existingStudent == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Student not found!");
        return;
    }

    String newName = nameTf.getText();
    String newEmail = emailTf.getText();

    if (!OOPAssignment.util.Validator.isEmpty(newName)) {
        existingStudent.setName(newName);
    }
    if (!OOPAssignment.util.Validator.isEmpty(newEmail)) {
        existingStudent.setEmail(newEmail);
    }

    existingStudent.save();

    javax.swing.JOptionPane.showMessageDialog(this, "Student updated successfully!");
    studentIdTf.setText("");
    nameTf.setText("");
    usernameTf.setText("");
    passwordTf.setText("");
    emailTf.setText("");
    refreshData();
    }//GEN-LAST:event_updateStudentBtnActionPerformed

    private void deleteStudentBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteStudentBtnActionPerformed
    String studentId = studentIdTf.getText();

    if (OOPAssignment.util.Validator.isEmpty(studentId)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter Student ID to delete!");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this student?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        boolean success = OOPAssignment.model.Student.deleteByStudentId(studentId);

        if (success) {
            javax.swing.JOptionPane.showMessageDialog(this, "Student deleted successfully!");
            studentIdTf.setText("");
            nameTf.setText("");
            usernameTf.setText("");
            passwordTf.setText("");
            emailTf.setText("");
            refreshData();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Student not found!");
        }
    }
    }//GEN-LAST:event_deleteStudentBtnActionPerformed


