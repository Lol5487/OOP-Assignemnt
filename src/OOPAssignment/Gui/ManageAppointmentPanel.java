    private void confirmBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmBtnActionPerformed
        String appointmentId = appointmentIdTf.getText();

        if (Validator.isEmpty(appointmentId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter appointment ID to confirm!");
            return;
        }

        Appointment appointment = Appointment.findById(appointmentId);
        if (appointment == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Appointment not found!");
            return;
        }

        appointment.setStatus("Confirmed");
        appointment.save();

        javax.swing.JOptionPane.showMessageDialog(this, "Appointment confirmed successfully!");
        appointmentIdTf.setText("");
        refreshData();
    }//GEN-LAST:event_confirmBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        String appointmentId = appointmentIdTf.getText();

        if (Validator.isEmpty(appointmentId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter appointment ID to update!");
            return;
        }

        Appointment appointment = Appointment.findById(appointmentId);
        if (appointment == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Appointment not found!");
            return;
        }

        java.util.Date selectedDate = (java.util.Date) dateSpinner.getValue();
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
        String newDate = sdf.format(selectedDate);

        String newTime = timeTf.getText();
        String newType = (String) typeCombo.getSelectedItem();

        if (!newDate.equals(appointment.getDate())) {
            appointment.setDate(newDate);
        }
        if (!Validator.isEmpty(newTime)) {
            appointment.setTime(newTime);
        }
        appointment.setType(newType);

        appointment.save();

        javax.swing.JOptionPane.showMessageDialog(this, "Appointment updated successfully!");
        appointmentIdTf.setText("");
        timeTf.setText("");
        refreshData();
    }//GEN-LAST:event_updateBtnActionPerformed


