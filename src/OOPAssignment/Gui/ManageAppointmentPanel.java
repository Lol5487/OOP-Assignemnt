    private void assignCounselorBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_assignCounselorBtnActionPerformed
        String appointmentId = appointmentIdTf.getText();
        String newCounselorUsername = counselorUsernameTf.getText();

        if (Validator.isEmpty(appointmentId) || Validator.isEmpty(newCounselorUsername)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter appointment ID and counselor username!");
            return;
        }

        Appointment appointment = Appointment.findById(appointmentId);
        if (appointment == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Appointment not found!");
            return;
        }

        appointment.setCounselorUsername(newCounselorUsername);
        appointment.save();

        javax.swing.JOptionPane.showMessageDialog(this, "Counselor assigned successfully!");
        refreshData();
    }//GEN-LAST:event_assignCounselorBtnActionPerformed

    private void cancelBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cancelBtnActionPerformed
        String appointmentId = appointmentIdTf.getText();

        if (Validator.isEmpty(appointmentId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter appointment ID to cancel!");
            return;
        }

        boolean success = Appointment.cancelById(appointmentId);

        if (success) {
            javax.swing.JOptionPane.showMessageDialog(this, "Appointment cancelled successfully!");
            appointmentIdTf.setText("");
            refreshData();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Appointment not found!");
        }
    }//GEN-LAST:event_cancelBtnActionPerformed

