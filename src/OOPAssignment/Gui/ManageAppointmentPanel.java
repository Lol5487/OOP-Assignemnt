    private void refreshData() {
        List<Appointment> all = Appointment.loadAll();

        String result = "=== All Appointments ===\n";
        if (all.isEmpty()) {
            result += "No appointments yet.\n";
        } else {
            for (Appointment a : all) {
                result += a.getAppointmentId() + " - Student: " + a.getStudentUsername()
                        + " - Counselor: " + a.getCounselorUsername()
                        + " - " + a.getDate() + " " + a.getTime()
                        + " - Type: " + a.getType()
                        + " (" + a.getStatus() + ")\n";
            }
        }
        appointmentListArea.setText(result);
    }


