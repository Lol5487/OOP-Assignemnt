    private void refreshData() {

        List<Appointment> allAppointments = Appointment.loadAll();
        String appointmentResult = "=== All Appointments ===\n";
        if (allAppointments.isEmpty()) {
            appointmentResult += "No appointments yet.\n";
        } else {
            for (Appointment a : allAppointments) {
                appointmentResult += a.getAppointmentId() + " - Student: " + a.getStudentUsername()
                        + " - Counselor: " + a.getCounselorUsername()
                        + " - " + a.getDate() + " " + a.getTime()
                        + " - Type: " + a.getType()
                        + " (" + a.getStatus() + ")\n";
            }
        }


        List<Student> allStudents = Student.loadAll();
        String studentResult = "=== Student List ===\n";
        if (allStudents.isEmpty()) {
            studentResult += "No students yet.\n";
        } else {
            for (Student s : allStudents) {
                String queueInfo = (s.getQueueNumber() == -1) ? "No queue number" : "Queue #" + s.getQueueNumber();
                studentResult += s.getStudentId() + " - " + s.getName() + " (" + s.getUsername() + ") - " + queueInfo + "\n";
            }
        }
        studentListArea.setText(studentResult);
    }
