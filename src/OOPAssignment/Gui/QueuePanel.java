    private void generateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_generateBtnActionPerformed
        String studentId = studentIdTf.getText();

        if (Validator.isEmpty(studentId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter Student ID!");
            return;
        }

        Student student = Student.findByStudentId(studentId);
        if (student == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Student not found!");
            return;
        }

        student.setQueueNumber(nextQueueNumber);
        student.save();

        resultLbl.setText("Queue number " + nextQueueNumber + " assigned to " + student.getName());
        nextQueueNumber++;
        studentIdTf.setText("");
        refreshData();
    }//GEN-LAST:event_generateBtnActionPerformed


